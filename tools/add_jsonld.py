#!/usr/bin/env python3
"""Inject one JSON-LD block per page (standard library only).

Run it after each build of the site: the HTML is generated by a build script
kept outside this repository, so the blocks are not part of that output.
Safe to rerun: the block carries id="jsonld-tonsite" and is replaced in place.

Blocks (one <script type="application/ld+json"> per page, with an @graph):
- every page except 404.html and demos/: Organization
- offre.html: plus one Offer per ".tier" card, name and price read from the page
- index.html: plus FAQPage built from the <details><summary> items, if any

Usage: python3 tools/add_jsonld.py [ROOT]
"""
import html
import json
import re
import sys
from pathlib import Path

SITE = "https://kamgangharold-ui.github.io/tonsite-beaute/"
BLOCK_ID = "jsonld-tonsite"
SKIP = {"404.html"}
BLOCK_RE = re.compile(
    r'[ \t]*<script type="application/ld\+json" id="%s">.*?</script>\n?' % BLOCK_ID, re.S)
TAG_RE = re.compile(r"<[^>]+>")


def text(fragment):
    return re.sub(r"\s+", " ", html.unescape(TAG_RE.sub("", fragment))).strip()


def organization():
    return {"@type": "Organization", "name": "tonsite.beaute", "url": SITE,
            "logo": SITE + "assets/logo-512.png"}


def offers(src):
    """One Offer per .tier card: name from its h2, price from its .price div."""
    out = []
    for body in re.split(r'<div class="card tier[^"]*">', src)[1:]:
        name = re.search(r"<h2[^>]*>(.*?)</h2>", body, re.S)
        price = re.search(r'<div class="price">\s*(\d+(?:[.,]\d+)?)\s*€', body)
        if not (name and price):
            continue
        out.append({"@type": "Offer", "name": text(name.group(1)),
                    "price": price.group(1).replace(",", "."), "priceCurrency": "EUR",
                    "url": SITE + "offre.html"})
    return out


def faq(src):
    items = []
    for q, a in re.findall(r"<details[^>]*>\s*<summary[^>]*>(.*?)</summary>(.*?)</details>", src, re.S):
        items.append({"@type": "Question", "name": text(q),
                      "acceptedAnswer": {"@type": "Answer", "text": text(a)}})
    return {"@type": "FAQPage", "mainEntity": items} if items else None


def graph_for(name, src):
    g = [organization()]
    if name == "offre.html":
        g += offers(src)
    if name == "index.html":
        f = faq(src)
        if f:
            g.append(f)
    return g


def render(graph):
    data = json.dumps({"@context": "https://schema.org", "@graph": graph},
                      ensure_ascii=False, indent=1).replace("</", "<\\/")
    return '<script type="application/ld+json" id="%s">\n%s\n</script>\n' % (BLOCK_ID, data)


def process(src, name):
    """Return the page with exactly one block, or None if it has no </head>."""
    src = BLOCK_RE.sub("", src)
    if "</head>" not in src:
        return None
    return src.replace("</head>", render(graph_for(name, src)) + "</head>", 1)


def main(argv):
    root = Path(argv[0] if argv else ".").resolve()
    changed = 0
    for p in sorted(root.glob("*.html")):
        if p.name in SKIP:
            continue
        old = p.read_text(encoding="utf-8")
        new = process(old, p.name)
        if new is None:
            print("skip (no </head>): " + p.name)
        elif new != old:
            p.write_text(new, encoding="utf-8")
            changed += 1
            print("updated: " + p.name)
    print("%d page(s) changed" % changed)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
