#!/usr/bin/env python3
"""Dependency free checker for the static site (standard library only).

Reads every *.html file and sitemap.xml under the given root and reports
errors (exit code 1) and warnings (exit code 0). The HTML is generated by a
build script kept outside this repository, so this tool never edits a file.

Usage: python3 tools/check_site.py [ROOT] [--report PATH]
"""
import argparse
import posixpath
import re
import sys
import xml.etree.ElementTree as ET
from html.parser import HTMLParser
from pathlib import Path
from urllib.parse import unquote, urlsplit

SKIP_DIRS = {".git", "node_modules", "tools"}
SKIP_PREFIXES = ("tests/fixtures",)
NOINDEX_PAGES = ("404.html",)
NOINDEX_DIRS = ("demos/",)
# Pages under demos/ are fictitious examples: their prices are not compared.
COMPARE_SKIP_DIRS = ("demos/",)

TRACKER_RE = re.compile(
    r"googletagmanager|google-analytics|\bgtag\s*\(|\bga\s*\(\s*['\"]|doubleclick|"
    r"googlesyndication|connect\.facebook\.net|\bfbq\s*\(|facebook\.com/tr|"
    r"plausible\.io|matomo|piwik|hotjar|clarity\.ms|mixpanel|segment\.(?:com|io)|"
    r"amplitude\.com|posthog|umami|fathom|analytics\.tiktok|linkedin\.com/px|"
    r"sendBeacon|hs-scripts|hubspot|intercom|tawk\.to|crisp\.chat|statcounter|"
    r"mc\.yandex|cloudflareinsights",
    re.I,
)
COOKIE_RE = re.compile(r"document\.cookie")

PRICE_RE = re.compile(
    r"(?<![\w.,])(?:€\s*(?P<n2>\d+(?:[   ]\d{3})*(?:[.,]\d{1,2})?)"
    r"|(?P<n1>\d+(?:[   ]\d{3})*(?:[.,]\d{1,2})?)\s*(?:€|euros?\b|EUR\b))",
    re.I,
)
DELAY_RE = re.compile(
    r"(?<!à )(?<![\w.,])(?P<n>\d+(?:[.,]\d+)?)\s*"
    r"(?P<u>heures?|jours?|semaines?|minutes?|mois|min|h|j)(?![\w])(?!\d)",
    re.I,
)
DELAY_HOURS = {"h": 1, "heure": 1, "jour": 24, "j": 24, "semaine": 168, "min": 1 / 60, "minute": 1 / 60}


class Finding:
    def __init__(self, level, code, page, line, message):
        self.level, self.code, self.page, self.line, self.message = level, code, page, line, message

    def key(self):
        return (self.level != "error", self.code, self.page, self.line or 0, self.message)

    def where(self):
        return f"{self.page}:{self.line}" if self.line else self.page


class PageParser(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.lang = None
        self.has_html = False
        self.ids = set()
        self.refs = []  # (tag, attr, value, line)
        self.scripts = []  # (src or None, inline text, line)
        self.h1_lines = []
        self.img_no_alt = []
        self.canonicals = []  # (href, line)
        self.robots = ""
        self.texts = []  # (text, line)
        self._skip = None
        self._script_line = None
        self._script_buf = []

    def handle_starttag(self, tag, attrs):
        a = {k: (v or "") for k, v in attrs}
        line = self.getpos()[0]
        if tag == "html":
            self.has_html = True
            self.lang = a.get("lang", None)
        if "id" in a:
            self.ids.add(a["id"])
        if tag == "a" and "name" in a:
            self.ids.add(a["name"])
        if tag == "h1":
            self.h1_lines.append(line)
        if tag == "img" and "alt" not in a:
            self.img_no_alt.append(line)
        if tag == "link" and "canonical" in a.get("rel", "").lower().split():
            self.canonicals.append((a.get("href", ""), line))
        if tag == "meta":
            name = (a.get("name") or a.get("property") or "").lower()
            if name == "robots":
                self.robots += " " + a.get("content", "").lower()
            if name in ("description", "og:description", "og:title"):
                self.texts.append((a.get("content", ""), line))
            if name in ("og:image", "twitter:image") and a.get("content"):
                self.refs.append((tag, "content", a["content"], line))
        if tag == "script":
            self._skip = "script"
            self._script_line = line
            self._script_buf = []
            self.scripts.append([a.get("src"), "", line])
        elif tag == "style":
            self._skip = "style"
        for attr in ("href", "src", "action"):
            if attr in a and tag in ("a", "area", "link", "img", "script", "source", "iframe", "audio", "video", "form", "embed"):
                if tag == "link" and "canonical" in a.get("rel", "").lower().split():
                    continue
                self.refs.append((tag, attr, a[attr], line))

    def handle_endtag(self, tag):
        if tag == self._skip:
            if tag == "script":
                self.scripts[-1][1] = "".join(self._script_buf)
            self._skip = None

    def handle_data(self, data):
        if self._skip == "script":
            self._script_buf.append(data)
        elif self._skip is None and data.strip():
            self.texts.append((data, self.getpos()[0]))


def find_pages(root):
    pages = []
    for p in sorted(root.rglob("*.html")):
        rel = p.relative_to(root).as_posix()
        if any(part in SKIP_DIRS or part.startswith(".") for part in p.relative_to(root).parts[:-1]):
            continue
        if rel.startswith(SKIP_PREFIXES):
            continue
        pages.append(rel)
    return pages


def line_of(text, needle):
    i = text.find(needle)
    return text.count("\n", 0, i) + 1 if i >= 0 else None


def load_sitemap(root, findings):
    """Return (base_url, {loc: relpath}) or (None, {})."""
    path = root / "sitemap.xml"
    if not path.exists():
        findings.append(Finding("error", "sitemap-invalid", "sitemap.xml", None, "sitemap.xml not found"))
        return None, {}
    raw = path.read_text(encoding="utf-8")
    try:
        tree = ET.fromstring(raw)
    except ET.ParseError as exc:
        findings.append(Finding("error", "sitemap-invalid", "sitemap.xml", None, f"XML parse error: {exc}"))
        return None, {}
    locs = [e.text.strip() for e in tree.iter() if e.tag.endswith("}loc") or e.tag == "loc" if e.text]
    dirs = [urlsplit(u).path.rsplit("/", 1)[0] + "/" for u in locs]
    base_path = posixpath.commonpath(dirs) if dirs else "/"
    base_path = base_path.rstrip("/") + "/"
    first = urlsplit(locs[0]) if locs else None
    base_url = f"{first.scheme}://{first.netloc}{base_path}" if first else None
    mapping = {}
    for loc in locs:
        rel = urlsplit(loc).path[len(base_path):] if urlsplit(loc).path.startswith(base_path) else None
        if rel is None:
            continue
        if rel == "" or rel.endswith("/"):
            rel += "index.html"
        mapping[loc] = rel
        if not (root / rel).is_file():
            findings.append(Finding("error", "sitemap-missing-page", "sitemap.xml", line_of(raw, loc),
                                    f"{loc} is listed but {rel} does not exist"))
    return base_url, mapping


def resolve(page, value, base_url):
    """Return (kind, rel_path, fragment): kind is internal, external, skip or escape."""
    value = value.strip()
    if not value:
        return "skip", None, None
    parts = urlsplit(value)
    if parts.scheme in ("mailto", "tel", "javascript", "data", "sms", "whatsapp"):
        return "skip", None, None
    frag = unquote(parts.fragment) if parts.fragment else ""
    if parts.scheme in ("http", "https") or value.startswith("//"):
        full = value if parts.scheme else "https:" + value
        if base_url and full.startswith(base_url):
            path = full[len(base_url):].split("#")[0].split("?")[0]
            return "internal", unquote(path) or "index.html", frag
        return "external", None, None
    if parts.scheme:
        return "skip", None, None
    path = unquote(parts.path)
    if path.startswith("/"):
        base_path = urlsplit(base_url).path if base_url else "/"
        if base_path != "/" and not path.startswith(base_path):
            return "escape", path, frag
        path = path[len(base_path):] if base_path != "/" else path.lstrip("/")
        joined = posixpath.normpath(path or ".")
    elif path == "":
        joined = page
    else:
        joined = posixpath.normpath(posixpath.join(posixpath.dirname(page), path))
    if joined.startswith("..") or joined == "..":
        return "escape", path, frag
    if path.endswith("/") or joined == ".":
        joined = posixpath.join(joined, "index.html") if joined != "." else "index.html"
    return "internal", joined, frag


def extract_quantities(texts):
    """Yield (kind, canonical value, surface form, line) for prices and delays."""
    out = []
    for text, line in texts:
        for m in PRICE_RE.finditer(text):
            num = (m.group("n1") or m.group("n2"))
            val = float(re.sub(r"[   ]", "", num).replace(",", "."))
            out.append(("price", val, norm_surface(m.group(0)), line + text.count("\n", 0, m.start())))
        for m in DELAY_RE.finditer(text):
            unit = m.group("u").lower().rstrip("s") if m.group("u").lower() != "mois" else "mois"
            n = float(m.group("n").replace(",", "."))
            val = (n, "mois") if unit == "mois" else (round(n * DELAY_HOURS[unit], 4), "h")
            out.append(("delay", val, norm_surface(m.group(0)), line + text.count("\n", 0, m.start())))
    return out


def norm_surface(s):
    return re.sub(r"[\s   ]+", " ", s.strip())


def check(root):
    root = Path(root)
    findings = []
    base_url, sitemap = load_sitemap(root, findings)
    site_host = urlsplit(base_url).netloc if base_url else None
    pages = find_pages(root)
    parsed = {}
    for rel in pages:
        p = PageParser()
        p.feed((root / rel).read_text(encoding="utf-8"))
        p.close()
        parsed[rel] = p
    by_file = {rel: loc for loc, rel in sitemap.items()}
    js_seen = {}
    quantities = {}

    def add(level, code, page, line, msg):
        findings.append(Finding(level, code, page, line, msg))

    for rel, p in parsed.items():
        # lang
        if not p.lang or not p.lang.strip():
            add("error", "missing-lang", rel, None, "html element has no lang attribute" if p.has_html else "no html element")
        # links and anchors
        for tag, attr, value, line in p.refs:
            kind, target, frag = resolve(rel, value, base_url)
            if kind == "escape":
                add("error", "broken-link", rel, line, f"{tag} {attr}={value!r} resolves outside the site base path")
            elif kind == "internal":
                tpath = root / target
                if not tpath.is_file():
                    add("error", "broken-link", rel, line, f"{tag} {attr}={value!r} points to {target}, which does not exist")
                elif frag and frag.lower() != "top" and target.endswith(".html"):
                    ids = parsed[target].ids if target in parsed else None
                    if ids is None:
                        q = PageParser()
                        q.feed(tpath.read_text(encoding="utf-8"))
                        ids = q.ids
                    if frag not in ids:
                        add("error", "broken-anchor", rel, line, f"{tag} {attr}={value!r}: no element with id {frag!r} in {target}")
            elif kind == "external":
                host = urlsplit(value if "://" in value else "https:" + value).netloc
                if TRACKER_RE.search(value):
                    add("error", "tracker", rel, line, f"{tag} {attr} loads a known tracker: {value}")
                elif tag == "script":
                    add("error", "external-script", rel, line, f"external script {value} (host {host})")
        # scripts: inline text and local files
        for src, inline, line in p.scripts:
            if inline and TRACKER_RE.search(inline):
                add("error", "tracker", rel, line, f"inline script matches tracker pattern {TRACKER_RE.search(inline).group(0)!r}")
            if inline and COOKIE_RE.search(inline):
                add("warning", "cookie-use", rel, line, "inline script uses document.cookie")
            if src:
                kind, target, _ = resolve(rel, src, base_url)
                if kind == "internal" and target.endswith(".js") and (root / target).is_file():
                    js_seen.setdefault(target, (root / target).read_text(encoding="utf-8"))
        # canonical
        if not p.canonicals:
            add("warning", "canonical-missing", rel, None, "no canonical link")
        else:
            href, line = p.canonicals[0]
            if len(p.canonicals) > 1:
                add("warning", "canonical-mismatch", rel, p.canonicals[1][1], "more than one canonical link")
            if rel in by_file and href != by_file[rel]:
                add("warning", "canonical-mismatch", rel, line, f"canonical {href} differs from sitemap URL {by_file[rel]}")
        # h1
        if len(p.h1_lines) != 1:
            add("warning", "h1-count", rel, p.h1_lines[1] if len(p.h1_lines) > 1 else None, f"{len(p.h1_lines)} h1 elements, expected exactly 1")
        for line in p.img_no_alt:
            add("warning", "img-alt", rel, line, "img without alt attribute")
        # noindex
        noindex = "noindex" in p.robots
        if (rel in NOINDEX_PAGES or rel.startswith(NOINDEX_DIRS)) and not noindex:
            add("warning", "missing-noindex", rel, None, "no meta robots noindex on a page that should not be indexed")
        if noindex and rel in by_file:
            add("warning", "noindex-in-sitemap", rel, None, "page is noindex but listed in sitemap.xml")
        if sitemap and not noindex and rel not in by_file:
            add("warning", "not-in-sitemap", rel, None, "indexable page is not listed in sitemap.xml")
        quantities[rel] = extract_quantities(p.texts)

    for target, text in sorted(js_seen.items()):
        for n, src_line in enumerate(text.splitlines(), 1):
            m = TRACKER_RE.search(src_line)
            if m:
                add("error", "tracker", target, n, f"script matches tracker pattern {m.group(0)!r}")
            if COOKIE_RE.search(src_line):
                add("warning", "cookie-use", target, n, "script uses document.cookie")

    findings.extend(compare_quantities(quantities))
    findings.sort(key=Finding.key)
    return findings, quantities


def compare_quantities(quantities):
    """Warn when one price or delay is written in more than one way across pages."""
    groups = {}
    for rel, items in quantities.items():
        if rel.startswith(COMPARE_SKIP_DIRS):
            continue
        for kind, val, surface, line in items:
            groups.setdefault((kind, val), {}).setdefault(surface.lower(), []).append((rel, line))
    out = []
    for (kind, val), forms in sorted(groups.items(), key=lambda kv: (kv[0][0], str(kv[0][1]))):
        if len(forms) < 2:
            continue
        detail = "; ".join(f"{s!r} at " + ", ".join(f"{r}:{l}" for r, l in locs) for s, locs in sorted(forms.items()))
        first = sorted(min(locs) for locs in forms.values())[0]
        out.append(Finding("warning", f"{kind}-variants", first[0], first[1],
                           f"same {kind} written differently: {detail}"))
    return out


def summary(findings):
    e = sum(f.level == "error" for f in findings)
    return e, len(findings) - e


def render_text(findings):
    lines = [f"{f.level.upper():7} {f.code:20} {f.where()}  {f.message}" for f in findings]
    e, w = summary(findings)
    lines.append(f"{e} error(s), {w} warning(s)")
    return "\n".join(lines)


CHECKS = [
    ("error", "broken-link", "Broken internal links"),
    ("error", "broken-anchor", "Broken anchors"),
    ("error", "sitemap-missing-page", "Page listed in sitemap.xml but missing"),
    ("error", "sitemap-invalid", "sitemap.xml unreadable"),
    ("error", "external-script", "External script tags"),
    ("error", "tracker", "Trackers"),
    ("error", "missing-lang", "Page without lang"),
    ("warning", "canonical-mismatch", "Canonical not matching the sitemap URL"),
    ("warning", "canonical-missing", "Canonical missing"),
    ("warning", "h1-count", "Not exactly one h1"),
    ("warning", "img-alt", "img without alt"),
    ("warning", "missing-noindex", "Missing noindex on demos/ and 404.html"),
    ("warning", "noindex-in-sitemap", "noindex page listed in the sitemap"),
    ("warning", "not-in-sitemap", "Indexable page absent from the sitemap"),
    ("warning", "cookie-use", "document.cookie used"),
    ("warning", "price-variants", "Same price written differently"),
    ("warning", "delay-variants", "Same delay written differently"),
]


def fix_location(page):
    if page.endswith(".html"):
        return "external build source (certain: README says the HTML is generated)"
    if page == "sitemap.xml":
        return "external build source (inference: sitemap.xml is probably generated with the pages)"
    return "this repository"


def render_markdown(findings, quantities):
    e, w = summary(findings)
    out = ["# Site check report", "",
           "Generated by `python3 tools/check_site.py --report tools/CHECK-REPORT.md`.",
           "", f"Result: **{e} error(s), {w} warning(s)**. Errors make the checker exit with code 1, warnings do not.", ""]
    out += ["Scope: every `*.html` page and `sitemap.xml`, plus local `.js` files loaded by a page. "
            "`tests/fixtures/` and `tools/` are skipped. The fixture pages are deliberately faulty `.html` files; "
            "GitHub Pages may serve them if it publishes the repository root (inference), though nothing links to them.", ""]
    for level, title in (("error", "Errors"), ("warning", "Warnings")):
        out += [f"## {title}", ""]
        for lv, code, label in CHECKS:
            if lv != level:
                continue
            hits = [f for f in findings if f.code == code]
            out.append(f"### {label} (`{code}`)")
            out.append("")
            if not hits:
                out += ["not found", ""]
                continue
            out += ["| Page and line | Finding | Fix in |", "|---|---|---|"]
            for f in hits:
                out.append(f"| `{f.where()}` | {f.message.replace('|', '/')} | {fix_location(f.page)} |")
            out.append("")
    out += ["## Prices and delays found per page", "",
            "Pages under `demos/` are fictitious examples and are left out of the mismatch comparison above. "
            "Delays are matched by pattern only, so a value may be a time of day or a duration rather than a delay (inference). A number written after the word \"à\" (as in \"à 9 h\") is skipped as a time of day.", "",
            "| Page | Prices | Delays |", "|---|---|---|"]
    for rel in sorted(quantities):
        def fmt(kind):
            seen = {}
            for k, _, s, line in quantities[rel]:
                if k == kind:
                    seen.setdefault(s, []).append(str(line))
            return ", ".join(f"`{s}` (l.{'/'.join(ls)})" for s, ls in seen.items()) or "not found"
        out.append(f"| `{rel}` | {fmt('price')} | {fmt('delay')} |")
    pages_html = sorted({f.page for f in findings if f.page.endswith(".html")})
    out += ["", "## What must be fixed in the external build source", ""]
    if pages_html:
        out += ["Every `.html` file here is generated, so any finding on these pages must be fixed in the build source, "
                "then the site rebuilt and copied here. A manual edit would be erased by the next rebuild: "
                + ", ".join(f"`{p}`" for p in pages_html) + ".", ""]
    else:
        out += ["not found: no finding on an `.html` page.", ""]
    other = sorted({f.page for f in findings if not f.page.endswith(".html") and f.page != "sitemap.xml"})
    if "sitemap.xml" in {f.page for f in findings}:
        out += ["`sitemap.xml` has findings. It is probably produced by the same build script (inference), "
                "so fix it there as well.", ""]
    if other:
        out += ["Findings on files kept in this repository: " + ", ".join(f"`{p}`" for p in other) + ".", ""]
    return "\n".join(out).rstrip() + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("root", nargs="?", default=".", help="site root (default: current directory)")
    ap.add_argument("--report", help="also write a Markdown report to this path")
    args = ap.parse_args(argv)
    findings, quantities = check(args.root)
    print(render_text(findings))
    if args.report:
        Path(args.report).write_text(render_markdown(findings, quantities), encoding="utf-8")
    return 1 if summary(findings)[0] else 0


if __name__ == "__main__":
    sys.exit(main())
